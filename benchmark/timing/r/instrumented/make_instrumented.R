## make_instrumented.R
##
## Generate the instrumented copies of the legacy R scripts used by the timing
## benchmark (TIMING_BENCHMARK_PLAN.md §6.8). The copies are generated from the
## files in legacy/R at run time, so they cannot silently drift from the originals:
## every edit is anchored on an exact line of the original and the generator stops if
## an anchor is missing or ambiguous.
##
## Two flavours are written for each script:
##   *_timed.R  timers added around blocks; computation unchanged
##   *_plain.R  only the path edits (no timers), used to prove with identical() that
##              the timers do not change any result
##
## Usage: Rscript make_instrumented.R <legacy_R_dir> <out_dir>

## ---- anchored line edits -------------------------------------------------------

## An edit: insert `text` before/after the line equal to `anchor` (after trimming
## whitespace), or replace that line. `after` restricts the search to lines below the
## first line equal to that string; `nth` picks one of several matches.
edit <- function(anchor, text, where = c("before", "after", "replace"), after = NULL, nth = 1L, timed_only = TRUE) {
  list(anchor = anchor, text = text, where = match.arg(where), after = after, nth = nth, timed_only = timed_only)
}

resolve <- function(lines, e, file) {
  t <- trimws(lines)
  start <- 1L
  if (!is.null(e$after)) {
    a <- which(t == e$after)
    if (length(a) == 0) stop(file, ": 'after' anchor not found: ", e$after)
    start <- a[1]
  }
  hits <- which(t == trimws(e$anchor))
  hits <- hits[hits >= start]
  if (length(hits) < e$nth) stop(file, ": anchor not found (", e$nth, "): ", e$anchor)
  if (e$nth == 1L && length(hits) > 1 && is.null(e$after)) {
    stop(file, ": anchor is ambiguous (", length(hits), " matches): ", e$anchor)
  }
  hits[e$nth]
}

apply_edits <- function(lines, edits, file, timed) {
  edits <- Filter(function(e) timed || !e$timed_only, edits)
  idx <- vapply(edits, resolve, 1L, lines = lines, file = file)
  ## Apply bottom-up. At the same line: "after" first, then "replace", then "before";
  ## among edits of the same kind, the last listed first, so that the listed order is
  ## kept in the output.
  rank <- match(vapply(edits, `[[`, "", "where"), c("before", "replace", "after"))
  ord <- order(idx, rank, seq_along(edits), decreasing = TRUE)
  for (k in ord) {
    e <- edits[[k]]; i <- idx[k]
    lines <- switch(e$where,
      before = append(lines, e$text, after = i - 1L),
      after = append(lines, e$text, after = i),
      replace = c(lines[seq_len(i - 1L)], e$text, lines[-seq_len(i)]))
  }
  lines
}

## ---- timer prelude --------------------------------------------------------------

PRELUDE <- c(
  "## ---- generated by benchmark/timing/r/instrumented/make_instrumented.R ----",
  "## Timers only; no computation of the original script is changed.",
  "if (!exists('.tm_now')) .tm_now <- if (requireNamespace('bench', quietly = TRUE)) bench::hires_time else function() proc.time()[['elapsed']]"
)

## Cheap accumulators for the sampling engine: .tmA[name] += elapsed.
acc_start <- function() ".tm_t <- .tm_now()"
acc_stop <- function(name) sprintf(".tmA[['%s']] <- .tmA[['%s']] + (.tm_now() - .tm_t)", name, name)
## Same, with a second clock so blocks can nest (outer blocks use .tm_u).
acc_start_outer <- function() ".tm_u <- .tm_now()"
acc_stop_outer <- function(name) sprintf(".tmA[['%s']] <- .tmA[['%s']] + (.tm_now() - .tm_u)", name, name)

## ---- lhs_sampling.R ----------------------------------------------------------------

LHS_SAMPLING_ACC <- c("time_series_df", "lhs", "transform", "split_chunks", "init", "chunk_loop",
                      "ts_alloc", "iw", "mvn", "normalise", "ts_block", "model_alloc", "model", "store",
                      "prcout", "model_block", "accept", "append")

lhs_sampling_edits <- function() list(
  edit("source(\"time_series_df.R\")", acc_start(), "before"),
  edit("source(\"time_series_df.R\")", acc_stop("time_series_df"), "after"),
  ## constants: one global LHS (second randomLHS call = the chunked branch)
  edit("parameters_lhs <- randomLHS(n_sample, n_parameters)", acc_start(), "before",
       after = "# sample the constant parameters from one large LHS and divide"),
  edit("parameters_lhs <- randomLHS(n_sample, n_parameters)", acc_stop("lhs"), "after",
       after = "# sample the constant parameters from one large LHS and divide"),
  edit("# constant parameter sampling", acc_start(), "before"),
  edit("# divide the scalar parameters across the chunks", c(acc_stop("transform"), acc_start()), "before"),
  edit("rm(list=c(\"par_calib_tmp\"))", acc_stop("split_chunks"), "after"),
  edit("par_calib_save <- NULL", acc_start(), "before"),
  edit("n_simulated <- 0 # total number of simulations actually run", acc_stop("init"), "after"),
  ## the chunk loop as a whole (orchestration = chunk_loop minus the blocks inside)
  edit("for (cc in 1:n_chunk) {", ".tm_c <- .tm_now()", "before"),
  edit("tend <- proc.time()", ".tmA[['chunk_loop']] <- .tmA[['chunk_loop']] + (.tm_now() - .tm_c)", "before"),
  ## time series
  edit("covariance_samples <- array(dim=c(n_time,n_time,n_sample_this_chunk[cc],n_parameters_time))",
       c(acc_start_outer(), acc_start()), "before"),
  edit("for (pp in 1:n_parameters_time) {", acc_stop("ts_alloc"), "before",
       after = "time_series_samples <- array(dim=c(n_time,n_sample_this_chunk[cc],n_parameters_time))"),
  edit("covariance_samples[,,,pp] <- rInvWishart(n_sample_this_chunk[cc], df[pp], (df[pp]-(n_time+1))*diag(par_time_stdev[,pp]^2))",
       acc_start(), "before"),
  edit("covariance_samples[,,,pp] <- rInvWishart(n_sample_this_chunk[cc], df[pp], (df[pp]-(n_time+1))*diag(par_time_stdev[,pp]^2))",
       acc_stop("iw"), "after"),
  edit("time_series_samples[,ii,pp] <- mvrnorm(n=1, mu=par_time_center[,pp], Sigma=covariance_samples[,,ii,pp])",
       acc_start(), "before"),
  edit("time_series_samples[,ii,pp] <- mvrnorm(n=1, mu=par_time_center[,pp], Sigma=covariance_samples[,,ii,pp])",
       c(acc_stop("mvn"), acc_start()), "after"),
  edit("time_series_samples[,ii,pp] <- time_series_samples[,ii,pp] - time_series_samples[n_time,ii,pp]",
       c("}", acc_stop("normalise")), "after"),
  edit("}", character(0), "replace",   # the closing brace of the normalisation if/else moves above the timer
       after = "time_series_samples[,ii,pp] <- time_series_samples[,ii,pp] - time_series_samples[n_time,ii,pp]"),
  ## model runs (outer clock .tm_u restarted for the model block)
  edit("model_co2_this_chunk <- model_temp_this_chunk <- model_o2_this_chunk <- mat.or.vec(nr=n_time, nc=n_sample_this_chunk[cc])",
       c(acc_stop_outer("ts_block"), acc_start_outer(), acc_start()), "before"),
  edit("for (ii in 1:n_sample_this_chunk[cc]) {", acc_stop("model_alloc"), "before",
       after = "prcout_co2 <- prcout_temp <- rep(NA, n_sample_this_chunk[cc])"),
  edit("model_out <- model_run(par_calib=par_calib[[cc]][ii,],", acc_start(), "before"),
  edit("model_co2_this_chunk[,ii] <- model_out[,\"co2\"]", c(acc_stop("model"), acc_start()), "before"),
  edit("prcout_co2[ii] <- percout(model_co2_this_chunk[,ii], windows$co2)", c(acc_stop("store"), acc_start()), "before"),
  edit("prcout_temp[ii] <- percout(model_temp_this_chunk[,ii], windows$temp)", acc_stop("prcout"), "after"),
  ## acceptance and appending
  edit("idx_save_temp <- which(prcout_temp <= prcout_threshold)", c(acc_stop_outer("model_block"), acc_start()), "before"),
  edit("n_simulated <- n_simulated + n_sample_this_chunk[cc]", c(acc_stop("accept"), acc_start()), "before"),
  edit("if (enough) {break}", acc_stop("append"), "before",
       after = "prcout_temp_save <- c(prcout_temp_save, prcout_temp[idx_save])")
)

