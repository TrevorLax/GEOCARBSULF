## pdf('../figures/x.pdf', ...) -> pdf(file.path(.FIG_DIR, 'x.pdf'), ...)
redirect_figures <- function(lines) {
  sub("pdf\\('\\.\\./figures/([^']+)'", "pdf(file.path(.FIG_DIR, '\\1')", lines)
}

## Drop the machine-specific setwd block (analysis_and_plots.R:17-28) after its first
## line was replaced, and the supplemental + Cretaceous part (lines 762-821), which
## needs the outputs of the supplemental and Cretaceous experiments.
drop_blocks <- function(lines, file) {
  t <- trimws(lines)
  i <- which(t == "setwd(.LEGACY_R_DIR)")
  if (length(i) != 1) stop(file, ": setwd replacement not found")
  j <- which(t == "setwd('~/work/codes/GEOCARB-precalibration/R')")
  if (length(j) != 1 || t[j + 1] != "}") stop(file, ": end of the setwd block not found")
  lines <- lines[-((i + 1):(j + 1))]
  t <- trimws(lines)
  a <- which(t == "## now, run the supplemental/sensitivity experiment analysis")
  b <- which(t == "## GYM experiment modification")
  if (length(a) != 1 || length(b) != 1 || b < a) stop(file, ": supplemental block anchors not found")
  ## keep the ##=== separator line right above "## GYM experiment modification"
  lines <- c(lines[seq_len(a - 1)],
             "## [benchmark] supplemental and Cretaceous analysis removed: they need the outputs of those experiments",
             lines[(b - 1):length(lines)])
  lines
}

## ---- main --------------------------------------------------------------------------

make_all <- function(legacy_r, out_dir) {
  dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
  rd <- function(f) readLines(file.path(legacy_r, f), warn = FALSE)
  wr <- function(lines, f) { writeLines(lines, file.path(out_dir, f)); file.path(out_dir, f) }

  src <- rd("lhs_sampling.R")
  out <- c(wr(c(LHS_SAMPLING_PRELUDE, apply_edits(src, lhs_sampling_edits(), "lhs_sampling.R", TRUE)), "lhs_sampling_timed.R"))

  src <- rd("lhs.R")
  out <- c(out, wr(c(PRELUDE, apply_edits(src, lhs_edits(), "lhs.R", TRUE)), "lhs_timed.R"),
           wr(apply_edits(src, lhs_edits(), "lhs.R", FALSE), "lhs_plain.R"))

  src <- rd("analysis_and_plots.R")
  for (timed in c(TRUE, FALSE)) {
    l <- apply_edits(src, analysis_edits(), "analysis_and_plots.R", timed)
    l <- drop_blocks(redirect_figures(l), "analysis_and_plots.R")
    if (any(grepl("\\.\\./figures/|\\.\\./output/", l))) stop("analysis_and_plots.R: a ../figures or ../output path was not redirected")
    out <- c(out, wr(if (timed) c(ANALYSIS_PRELUDE, l) else l,
                     if (timed) "analysis_and_plots_timed.R" else "analysis_and_plots_plain.R"))
  }
  invisible(out)
}

args <- commandArgs(trailingOnly = TRUE)
if (length(args) == 2) {
  files <- make_all(normalizePath(args[1], winslash = "/", mustWork = TRUE), args[2])
  cat(paste("wrote", files), sep = "\n")
}
